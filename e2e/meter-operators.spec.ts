import { expect, test } from '@playwright/test'

test('executes attributed custody, independent certificate review and permitted closure on case dates', async ({ page }) => {
  await page.goto('/meter-exchange')
  await page.getByLabel('Workload role').selectOption('Operations Supervisor')
  await page.getByRole('button', { name: 'Coordinate urgent meter follow-up' }).click()
  await page.getByLabel('Custody execution operator').selectOption('METER-INACTIVE')
  await page.getByLabel('Meter business date').fill('2026-10-24')
  await page.getByRole('button', { name: 'Advance disposal custody' }).click()
  await expect(page.getByRole('status')).toContainText('inactive')
  await expect(page.getByRole('status')).toBeFocused()
  await page.getByRole('button', { name: 'Refresh selected meter case' }).click()
  await expect(page.getByLabel('Meter business date')).toHaveValue('2026-10-24')
  await page.getByLabel('Custody execution operator').selectOption('METER-FIELD')
  for (let i = 0; i < 4; i++) await page.getByRole('button', { name: 'Advance disposal custody' }).click()
  await page.getByLabel('Disposal certificate review evidence').fill('INDEPENDENT-CERTIFICATE-REVIEW-905')
  await page.getByLabel('Certificate review operator').selectOption('METER-FIELD')
  await page.getByRole('button', { name: 'Accept disposal certificate' }).click()
  await expect(page.getByRole('status')).toContainText('Independent reviewer')
  await page.getByLabel('Certificate review operator').selectOption('METER-REVIEW')
  await page.getByLabel('Meter business date').fill('2026-10-23')
  await page.getByRole('button', { name: 'Accept disposal certificate' }).click()
  await expect(page.getByRole('status')).toContainText('valid date')
  await page.getByLabel('Meter business date').fill('2026-10-25')
  await page.getByRole('button', { name: 'Accept disposal certificate' }).click()
  const history = page.getByRole('list', { name: 'Meter disposal custody history' })
  await expect(history).toContainText('METER-FIELD')
  await expect(history).toContainText('METER-REVIEW')
  await expect(history).toContainText('2026-10-25')
  await page.getByRole('button', { name: 'Close reconciled meter case' }).click()
  await expect(page.getByRole('status')).toContainText('not authorized')
  await page.getByLabel('Custody execution operator').selectOption('METER-CUSTODY')
  await page.getByRole('button', { name: 'Close reconciled meter case' }).click()
  await expect(page.getByRole('list', { name: 'Meter closure history' })).toContainText('custody DISPOSAL-905')
  await expect(page.getByRole('list', { name: 'Meter closure history' })).toContainText('METER-CUSTODY')
  await page.reload()
  await expect(history).toContainText('METER-REVIEW')
  await expect(page.getByLabel('Custody execution operator')).toHaveValue('METER-CUSTODY')
})
